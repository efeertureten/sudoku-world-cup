export type Locale = 'tr' | 'en';
const DICTIONARIES: Record<Locale, Dictionary> = { tr, en };

const stored = (() => {
  try {
    return localStorage.getItem('swc.locale') as Locale | null;
  } catch {
    return null;
  }
})();
const initial: Locale = stored ?? (navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en');

export const useLocale = create<{ locale: Locale; setLocale: (l: Locale) => void }>((set) => ({
  locale: initial,
  setLocale: (locale) => {
    try {
      localStorage.setItem('swc.locale', locale);
    } catch {
      /* private mode */
    }
    document.documentElement.lang = locale;
    set({ locale });
  },
}));

/**
 * Singular forms, used when `{n}` is 1. Turkish keeps the noun singular after
 * any number, so only English needs entries.
 */
const SINGULAR: Record<Locale, Partial<Dictionary>> = {
  tr: {},
  en: {
    'cup.humans': '{n} player',
    'home.nextLeague': '{n} trophy to {league}',
    'locker.coins': '{n} coin',
    'standings.contributorsCount': '{n} player',
    'standings.seasonEnds': 'Season {s} ends in {n} day',
  },
};

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  const singular = vars?.n === 1 ? SINGULAR[locale][key] : undefined;
  let text = singular ?? DICTIONARIES[locale][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

export function useT() {
  const locale = useLocale((s) => s.locale);
  return (key: MessageKey, vars?: Record<string, string | number>) => translate(locale, key, vars);
}
